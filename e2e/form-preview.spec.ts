import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
for(const width of [1280,390])test('basic info previews transformed appearance, types, abilities and stats at '+width,async({page})=>{
 await page.setViewportSize({width,height:width===1280?800:900});
 const registration=await page.request.post('/api/account',{headers:{origin:'http://127.0.0.1:3001'},data:{action:'register',username:'forms_'+randomUUID().slice(0,8),password:'preview-form-password'}});expect(registration.status()).toBe(200);
 await page.goto('/pokedex');await page.getByRole('button',{name:'리자몽 상세 보기',exact:true}).click();await page.getByRole('button',{name:'포켓몬 정보',exact:true}).click();
 const summary=page.getByTestId('dex-detail');
 await expect(summary.locator('.stat-details')).toHaveCount(0);
 await expect(summary).not.toContainText('모습 미리보기');
 await expect(summary.locator('.summary-traits>div').last().locator('dd')).toHaveText('성실');
 await expect(summary.getByRole('tooltip')).toBeHidden();
 await summary.locator('.summary-ability').hover();
 await expect(summary.getByRole('tooltip')).toBeVisible();
 await expect(summary.getByRole('tooltip')).not.toBeEmpty();
 await page.mouse.move(0,0);
 await expect(summary.getByRole('tooltip')).toBeHidden();
 await expect(summary.locator('.summary-hero h2')).toHaveText('리자몽');
 await page.keyboard.press('ArrowRight');
 await expect(summary.locator('.summary-hero h2')).toHaveText('메가리자몽X');
 await expect(summary.locator('.summary-types span')).toHaveText(['불꽃','드래곤']);
 await expect(summary.locator('.summary-traits')).toContainText('단단한발톱');
 await summary.locator('.summary-ability').hover();
 await expect(summary.getByRole('tooltip')).toContainText('접촉');
 await summary.screenshot({path:'test-results/ability-tooltip-'+width+'.png'});
 await page.mouse.move(0,0);
 await expect(summary.locator('.summary-stat-list dd')).toHaveText(['78','130','111','130','85','100']);
 await expect(summary.locator('.summary-sprite img')).toHaveAttribute('src',/charizard-megax/);
 await summary.screenshot({path:'test-results/form-mega-x-'+width+'.png'});
 await page.keyboard.press('ArrowRight');
 await expect(summary.locator('.summary-hero h2')).toHaveText('메가리자몽Y');
 await expect(summary.locator('.summary-types span')).toHaveText(['불꽃','비행']);
 await expect(summary.locator('.summary-traits')).toContainText('가뭄');
 await expect(summary.locator('.summary-stat-list dd')).toHaveText(['78','104','78','159','115','100']);
 await page.keyboard.press('ArrowRight');
 await expect(summary.locator('.summary-hero h2')).toHaveText('거다이맥스 리자몽');
 await expect(summary.locator('.summary-stat-list dd')).toHaveText(['78','84','78','109','85','100']);
 await expect(summary).toHaveAttribute('data-preview-form','Charizard-Gmax');
 await expect.poll(()=>summary.locator('.summary-sprite img').evaluate(img=>(img as HTMLImageElement).naturalWidth),{timeout:20000}).toBeGreaterThan(0);
 expect(await summary.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
 if(width===1280){const bounds=await summary.locator('xpath=ancestor::dialog').evaluate(el=>({content:el.scrollHeight,visible:el.clientHeight}));expect(bounds.content).toBeLessThanOrEqual(bounds.visible);}
 await summary.screenshot({path:'test-results/form-gigantamax-'+width+'.png'});
 await summary.getByRole('button',{name:'기본 모습',exact:true}).click();
 await expect(summary.locator('.summary-hero h2')).toHaveText('리자몽');
 await expect(summary.locator('.summary-types span')).toHaveText(['불꽃','비행']);
 const collection=await page.request.get('/api/battle?view=collection').then(r=>r.json());
 expect(collection.training.find((entry:{species:string})=>entry.species==='Charizard').profile.ability).toBe('Blaze');
 await page.keyboard.press('x');
 await page.getByRole('button',{name:'리자몽 상세 보기',exact:true}).click();
 await page.getByRole('button',{name:'능력치 조정',exact:true}).click();
 const editor=page.getByTestId('training-editor');
 await editor.getByRole('tab',{name:'성격·특성·테라스탈',exact:true}).click();
 const dimensions=await editor.locator('.training-trait-button').evaluateAll(buttons=>buttons.map(button=>({width:button.getBoundingClientRect().width,height:button.getBoundingClientRect().height,left:button.getBoundingClientRect().left})));
 expect(dimensions).toHaveLength(3);
 expect(dimensions[1]).toEqual(dimensions[0]);
 expect(dimensions[2]).toEqual(dimensions[0]);
 await page.getByRole('dialog',{name:'리자몽 능력치 조정',exact:true}).screenshot({path:'test-results/dex-traits-aligned-'+width+'.png'});
});
