import {test,expect} from '@playwright/test';
import {randomBytes} from 'node:crypto';
import {TowerStore} from '../src/server/tower-store';
import {playerKey} from '../src/server/tower-service';
import {classicCollection} from '../tests/classic-team-fixture';

for(const width of [1280,390])test(`title, dex return and move zone keyboard navigation at ${width}`,async({page,context})=>{
  const token=randomBytes(32).toString('hex'),store=new TowerStore('.data/e2e.sqlite');
  try{store.ensurePlayer(playerKey(token));classicCollection(store,playerKey(token));}finally{store.close();}
  await context.addCookies([{name:'tower_session',value:token,url:'http://127.0.0.1:3001',httpOnly:true,sameSite:'Strict'}]);
  await page.setViewportSize({width,height:900});await page.goto('/');
  await expect(page.locator('.title-play')).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('link',{name:'포켓몬 도감',exact:true})).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('z');await expect(page).toHaveURL(/\/pokedex$/);
  await expect(page.getByTestId('dex-progress')).toHaveText('27 / 612');
  const favorite=page.locator('.dex-card-wrap:has(.dex-card[aria-pressed=true]) .dex-favorite');
  await page.keyboard.press('f');await expect(favorite).toHaveAttribute('aria-pressed','true');
  const favoritesFilter=page.locator('.dex-favorites-filter');
  await page.keyboard.press('v');await expect(favoritesFilter).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.dex-list .dex-card')).toHaveCount(1);
  await page.keyboard.press('v');await expect(favoritesFilter).toHaveAttribute('aria-pressed','false');
  await page.keyboard.press('v');await page.keyboard.press('r');await expect(favoritesFilter).toHaveAttribute('aria-pressed','false');
  await expect(page.getByRole('button',{name:'필터 초기화 · R',exact:true})).toBeDisabled();
  await page.keyboard.press('f');await expect(favorite).toHaveAttribute('aria-pressed','false');
  const card=page.getByRole('button',{name:'리자몽 상세 보기',exact:true});await card.click();
  await page.keyboard.press('z');await expect(page.locator('.dex-party-slot strong')).toHaveText('리자몽');
  await page.keyboard.press('x');
  const confirmation=page.getByRole('dialog',{name:'타이틀 화면으로 돌아가시겠습니까?'});
  await expect(confirmation).toBeVisible();await expect(page.locator('.dex-party-slot strong')).toHaveText('리자몽');
  await page.keyboard.press('x');await expect(confirmation).toHaveCount(0);
  await page.keyboard.press('z');await page.keyboard.press('z');
  await expect(page.locator('.dex-party-slot strong')).toHaveCount(0);
  await card.click();await page.keyboard.press('3');
  const editor=page.locator('.move-editor'),library=editor.locator('.move-library');
  const move=library.locator('button').filter({has:page.getByText('회오리불꽃',{exact:true})});
  await expect(editor.locator('.move-slots button').first()).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('z');await expect(library.locator('[data-game-cursor=true]')).toHaveCount(1);
  const original=(await editor.locator('.move-slots button').first().textContent()) ?? '';
  await page.keyboard.press('x');await expect(editor).toBeVisible();
  await expect(editor.locator('.move-slots button.selected')).toHaveAttribute('data-game-cursor','true');
  await expect(editor.locator('.move-slots button').first()).toHaveText(original);
  await page.keyboard.press('z');await expect(library.locator('[data-game-cursor=true]')).toHaveCount(1);
  await move.click();
  await expect(editor.locator('.move-slots button.selected')).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('z');await expect(move).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('z');await expect(editor.locator('.move-slots button.selected')).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('ArrowDown');await expect(library.locator('[data-game-cursor=true]')).toHaveCount(1);
  await page.keyboard.press('x');await expect(editor.locator('.move-slots button.selected')).toHaveAttribute('data-game-cursor','true');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('z');await expect(page.getByRole('status')).toHaveText('설정 저장 완료');
  await expect(editor.locator('.move-help')).toHaveCount(0);
  await expect(page.locator('.dex-save-notice')).toHaveCount(0,{timeout:4000});
  await page.keyboard.press('x');await page.keyboard.press('x');await expect(confirmation).toBeVisible();
  await page.keyboard.press('ArrowDown');await page.keyboard.press('z');await expect(page).toHaveURL(/\/$/);
  await page.keyboard.press('ArrowDown');await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/\/upgrades$/);
  await expect(page.locator('.permanent-products section')).toHaveCount(2);
  await expect(page.locator('.egg-station h2')).toHaveText('알 뽑기');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
