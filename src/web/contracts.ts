  upgrades: {kind:UpgradeKind; remainingFloors:number}[];
  consumableOffers?:UpgradeKind[];
  heldItems?:Record<string,string>;
  itemBag?:Record<string,number>;
  teraTickets?:number;
  teraShop?:{price:number;purchased:boolean}|null;
  itemPurchases?:string[];
  itemOffers?:string[];
