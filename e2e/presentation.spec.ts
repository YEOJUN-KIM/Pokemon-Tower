import {test,expect} from '@playwright/test';
import {selectStarters} from './select-starters';
test('attack and hit feedback without projectiles; sound and settings persist',async({page})=>{
  const cryRequests:string[]=[];
  page.on('request',request=>{if(request.url().includes('/audio/cries/'))cryRequests.push(request.url());});
  await page.route('**/audio/cries/*.ogg',route=>route.fulfill({status:404,body:''}));
  await page.addInitScript(()=>{
    const original=AudioContext.prototype.createOscillator;
    (window as unknown as {tones:number}).tones=0;
    AudioContext.prototype.createOscillator=function(){(window as unknown as {tones:number}).tones++;return original.call(this);};
  });
  await page.route('**/audio/battle-bgm.mp3',route=>route.fulfill({status:404,body:''}));
  await page.goto('/battle');
  await selectStarters(page);
  await page.getByRole('button',{name:'새 도전 시작'}).click();await page.getByRole('button',{name:'이 룰로 도전 시작',exact:true}).click();await page.getByRole('button',{name:'포켓몬 내보내기',exact:true}).click();
  await expect(page.locator('.send-out')).toBeVisible();
  await expect(page.locator('.arena')).toHaveAttribute('data-playing','false');
  await expect(page.getByTestId('action-grid')).toBeVisible();
  expect(await page.evaluate(()=>(window as unknown as {tones:number}).tones)).toBe(0);
  await page.getByRole('button',{name:'소리 켜기',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>(window as unknown as {tones:number}).tones)).toBeGreaterThan(2);
  await page.locator('[data-command="move 1"]').click();
  await expect(page.locator('.arena')).toHaveAttribute('data-playing','true');
  await expect(page.locator('.motion-move')).toBeVisible();
  await expect(page.locator('.move-effect')).toHaveCount(0);
  await expect(page.locator('[data-command="move 1"]')).toBeDisabled();
  await expect(page.locator('.motion-hit')).toBeVisible();
  await expect(page.locator('.motion-hit')).toHaveCSS('animation-name','hit-blink');
  await page.screenshot({path:'test-results/move-animation.png',fullPage:true});
  await expect(page.locator('.arena')).toHaveAttribute('data-playing','false');
  const result=await page.request.get('/api/battle').then(r=>r.json());
  const active=result.battle.team.find((p:{active:boolean})=>p.active);
  await expect(page.locator('.player-health .hp-number')).toHaveText(active.condition.includes('fnt') ? '기절' : active.condition.split(' ')[0]);
  await page.getByRole('button',{name:'교체 · A',exact:true}).click();
  await page.locator('[data-command="switch 2"]').click();
  await expect.poll(()=>cryRequests.some(url=>url.endsWith('/9.ogg'))).toBe(true);
  await expect(page.locator('.arena')).toHaveAttribute('data-playing','false');
  await page.getByRole('button',{name:'소리 끄기',exact:true}).click();
  await page.waitForTimeout(400);
  const mutedCount=await page.evaluate(()=>(window as unknown as {tones:number}).tones);
  await page.waitForTimeout(500);
  expect(await page.evaluate(()=>(window as unknown as {tones:number}).tones)).toBe(mutedCount);
  await page.goto('/settings');
  await expect(page.getByRole('checkbox')).toBeChecked();
  await page.getByRole('slider',{name:'BGM 크기'}).fill('20');
  await page.reload();
  await expect(page.getByRole('slider',{name:'BGM 크기'})).toHaveValue('20');
});
